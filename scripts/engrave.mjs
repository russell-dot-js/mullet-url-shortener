// Engraves jvm/Mint.j: a 62-slot check table built inside <clinit>, plus the two methods that consume it.
// The seed is the only input. Re-engraving reproduces the instruction sheet byte for byte.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const SEED = 62062011;
export const BASE = 62;

// Fisher-Yates with a fixed linear congruential generator.
export function permutation(seed = SEED, size = BASE) {
  const values = Array.from({ length: size }, (_, index) => index);
  let state = seed >>> 0;
  for (let index = size - 1; index > 0; index--) {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    const pick = state % (index + 1);
    [values[index], values[pick]] = [values[pick], values[index]];
  }
  return values;
}

function tableSheet(table) {
  const lines = [];
  table.forEach((value, index) => {
    lines.push(
      "    getstatic Mint/table [I",
      `    bipush ${index}`,
      `    bipush ${value}`,
      "    iastore",
    );
  });
  return lines;
}

export function engrave(seed = SEED) {
  const table = permutation(seed);
  return [
    "; Autogenerated by scripts/engrave.mjs. Do not hand-edit: change the seed and re-engrave.",
    "; Mint owns the check slot. Node asks for it and never computes it.",
    ".class public Mint",
    ".super java/lang/Object",
    "",
    ".field private static table [I",
    "",
    "; The 62-slot check table is written out one slot at a time, so the sheet is long on purpose.",
    ".method static <clinit>()V",
    "    .limit stack 3",
    "    .limit locals 0",
    "    bipush 62",
    "    newarray int",
    "    putstatic Mint/table [I",
    ...tableSheet(table),
    "    return",
    ".end method",
    "",
    "; Folds the base-62 digits of a payload least-significant first, then maps the fold into the table.",
    ".method public static checkIndex(I)I",
    "    .limit stack 4",
    "    .limit locals 4",
    "    iconst_0",
    "    istore_1",
    "    iload_0",
    "    istore_2",
    "digest:",
    "    iload_2",
    "    ifeq folded",
    "    iload_1",
    "    iconst_3",
    "    imul",
    "    iload_2",
    "    bipush 62",
    "    irem",
    "    iadd",
    "    istore_1",
    "    iload_2",
    "    bipush 62",
    "    idiv",
    "    istore_2",
    "    goto digest",
    "folded:",
    "    iload_1",
    "    bipush 7",
    "    imul",
    "    bipush 11",
    "    iadd",
    "    bipush 62",
    "    irem",
    "    istore_3",
    "    getstatic Mint/table [I",
    "    iload_3",
    "    iaload",
    "    ireturn",
    ".end method",
    "",
    ".method public static verdict(II)I",
    "    .limit stack 2",
    "    .limit locals 2",
    "    iload_0",
    "    invokestatic Mint/checkIndex(I)I",
    "    iload_1",
    "    if_icmpne refused",
    "    iconst_1",
    "    ireturn",
    "refused:",
    "    iconst_0",
    "    ireturn",
    ".end method",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(process.argv[2] ?? "jvm/Mint.j", engrave());
}
