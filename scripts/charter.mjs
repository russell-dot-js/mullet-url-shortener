// The printing press is centralized. Liability for its output is decentralized.
import { readFileSync, writeFileSync } from "node:fs";

import { syndicate } from "./syndication.mjs";

const [charterFile, output, count] = process.argv.slice(2);
if (!output) throw Error("Usage: node charter.mjs constitution.json statute-book.mjs [layers]");
const charter = JSON.parse(readFileSync(charterFile, "utf8"));
const layers = Number(count ?? charter.layers ?? 200);
if (!Number.isSafeInteger(layers) || layers < 1) throw Error("layers must be a positive integer");
const { offices, hearings } = charter;
if (!offices.length || !hearings.length) throw Error("Every legislature needs an office and a hearing");

const source = ["// Autogenerated legislation. Amend the constitution and reconvene the printing press.", "export default ["];
for (let seat = 0; seat < layers; seat++) {
  const [office, mandate] = offices[seat % offices.length];
  const [hearing, procedure, finding] = hearings[Math.floor(seat / offices.length) % hearings.length];
  const article = {
    title: hearing + " before " + office,
    office,
    mandate,
    procedure,
    finding,
    reading: 1 + Math.floor(seat / (offices.length * hearings.length)),
  };
  const clauses = JSON.stringify(article, null, 2).slice(0, -2);
  source.push(clauses + ",");
  if (charter.franchises?.length) source.push(syndicate(office, hearing, seat, article.reading, charter.franchises));
  source.push(
    "  sit(clerk, treasury, previousSeal) {",
    "    const motion = clerk.takeRoll(this, previousSeal);",
    "    const disposition = motion.carried",
    "      ? clerk.enact(this, treasury)",
    "      : clerk.remand(this, treasury);",
    "    return { motion, disposition };",
    "  }",
    "},");
}
source.push("];", "");
writeFileSync(output, source.join("\n"));
